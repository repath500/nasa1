import { PRESETS } from '@fire/contracts';
import { ApiError, json, readJsonBody } from '../http.ts';
import { geminiConfigured, type Env } from '../env.ts';
import { ExplainRequestSchema } from '../ai/schemas.ts';
import { explainWithHydrogen, type ModelCallOptions } from '../ai/hydrogen.ts';
import { claimLint, numberGuard } from '../core-bridge.ts';
import { studyByAccession } from '../ai/studies.ts';

const fmt = (n: number): string => (Number.isInteger(n) ? String(n) : String(Math.round(n * 10) / 10));

export const templateExplanation = (
  accession: string,
  scenarioId: keyof typeof PRESETS,
): { text: string; claimIds: string[] } | null => {
  const study = studyByAccession(accession);
  const scenario = PRESETS[scenarioId];
  if (!study || !scenario) return null;
  return {
    text:
      study.accession +
      ' (' +
      study.acronym +
      ') is a microgravity ' +
      study.phases.join(' and ') +
      ' study. The preset ' +
      scenario.label +
      ' is shown at ' +
      fmt(scenario.o2Pct) +
      ' percent oxygen and ' +
      fmt(scenario.totalKpa) +
      ' kPa. The atlas lists matching rows and their limitations. This sentence is generated by code from corpus fields, not by a model.',
    claimIds: [study.accession, 'scenario:' + scenario.id],
  };
};

export const explain = async (req: Request, env: Env, options?: ModelCallOptions): Promise<Response> => {
  const body = await readJsonBody(req);
  const parsed = ExplainRequestSchema.safeParse(body);
  if (!parsed.success) throw new ApiError(400, 'Invalid explain request');
  const { accession, scenarioId } = parsed.data;
  const study = studyByAccession(accession);
  if (!study) throw new ApiError(400, 'Study not in the allowlist');
  const scenario = PRESETS[scenarioId];
  if (!scenario) throw new ApiError(400, 'Unknown scenario');

  const fallback = templateExplanation(accession, scenarioId);
  if (!fallback) throw new ApiError(400, 'Unknown study');

  if (geminiConfigured(env)) {
    try {
      const result = await explainWithHydrogen(
        env,
        {
          accession: study.accession,
          acronym: study.acronym,
          scenarioLabel: scenario.label,
          o2Pct: scenario.o2Pct,
          totalKpa: scenario.totalKpa,
        },
        options,
      );
      const allowedClaims = new Set([study.accession, 'scenario:' + scenario.id, 'scenario:' + scenario.label]);
      const numbers = numberGuard(result.text, [scenario.o2Pct, scenario.totalKpa]);
      const claims = claimLint(result.text);
      if (
        numbers.ok &&
        claims.ok &&
        result.claimIds.length > 0 &&
        result.claimIds.every((id) => allowedClaims.has(id))
      ) {
        return json({ text: result.text, claimIds: result.claimIds, source: 'hydrogen' });
      }
    } catch {
      // fall through to the code template
    }
  }

  return json({ text: fallback.text, claimIds: fallback.claimIds, source: 'template' });
};
